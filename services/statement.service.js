const PDFDocument = require('pdfkit');

class StatementService {
  generateCSV(transactions) {
    const headers = ['ID', 'Date', 'Type', 'Asset', 'Amount', 'Amount_USD', 'Fee', 'Status', 'TX_Hash', 'Notes'];
    const rows = transactions.map(t => [
      t.id,
      new Date(t.created_at).toISOString(),
      t.type,
      t.asset_symbol,
      t.amount,
      t.amount_usd,
      t.fee || 0,
      t.status,
      t.tx_hash || 'N/A',
      `"${(t.notes || '').replace(/"/g, '""')}"`
    ]);

    const csvContent = [headers.join(','), ...rows.map(r => r.join(','))].join('\n');
    return csvContent;
  }

  generatePDF(user, transactions, res) {
    const doc = new PDFDocument({ margin: 40, size: 'A4' });

    // Stream directly to Express response
    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader('Content-Disposition', `attachment; filename="Fichain_Audit_Statement_${user.account_id}.pdf"`);
    doc.pipe(res);

    // Header Design
    doc.fillColor('#0f172a').rect(0, 0, 600, 90).fill();

    doc.fillColor('#38bdf8').fontSize(22).font('Helvetica-Bold').text('FICHAIN PRO', 40, 25);
    doc.fillColor('#94a3b8').fontSize(10).font('Helvetica').text('INSTITUTIONAL AUDIT & TRADING STATEMENT', 40, 52);

    doc.fillColor('#ffffff').fontSize(10).text(`Statement Date: ${new Date().toLocaleDateString()}`, 400, 28, { align: 'right' });
    doc.text(`Account ID: ${user.account_id}`, 400, 44, { align: 'right' });
    doc.text(`Status: Verified Pro`, 400, 60, { align: 'right' });

    // Client Summary Section
    doc.moveDown(4);
    doc.fillColor('#0f172a').fontSize(14).font('Helvetica-Bold').text('Account Holder Summary', 40, 110);
    doc.strokeColor('#cbd5e1').lineWidth(1).moveTo(40, 130).lineTo(555, 130).stroke();

    doc.fillColor('#334155').fontSize(10).font('Helvetica');
    doc.text(`Name: ${user.full_name}`, 40, 140);
    doc.text(`Email: ${user.email}`, 40, 155);
    doc.text(`Jurisdiction: ${user.country || 'Global'}`, 40, 170);

    doc.text(`KYC Status: ${user.kyc_status.toUpperCase()}`, 320, 140);
    doc.text(`Role: Institutional ${user.role.toUpperCase()}`, 320, 155);
    doc.text(`Audit Classification: SEC / FinCEN Compliant Sandbox`, 320, 170);

    // Transactions Table
    doc.moveDown(3);
    doc.fillColor('#0f172a').fontSize(14).font('Helvetica-Bold').text('Verified Transaction Ledger', 40, 205);
    doc.strokeColor('#cbd5e1').lineWidth(1).moveTo(40, 225).lineTo(555, 225).stroke();

    // Table Header
    let y = 235;
    doc.fillColor('#64748b').fontSize(9).font('Helvetica-Bold');
    doc.text('Date', 40, y);
    doc.text('Type', 130, y);
    doc.text('Asset', 200, y);
    doc.text('Amount', 260, y);
    doc.text('Value (USD)', 350, y);
    doc.text('Status', 440, y);
    doc.text('Ref Hash', 500, y);

    y += 15;
    doc.strokeColor('#e2e8f0').lineWidth(0.5).moveTo(40, y).lineTo(555, y).stroke();
    y += 10;

    doc.font('Helvetica').fontSize(8).fillColor('#1e293b');
    const tableRows = transactions.slice(0, 20);

    for (const tx of tableRows) {
      if (y > 750) {
        doc.addPage();
        y = 40;
      }

      const dateStr = new Date(tx.created_at).toLocaleDateString();
      const refStr = (tx.tx_hash || 'TX-LOCAL').slice(0, 8) + '...';

      doc.text(dateStr, 40, y);
      doc.text(tx.type.toUpperCase(), 130, y);
      doc.text(tx.asset_symbol, 200, y);
      doc.text(parseFloat(tx.amount).toFixed(4), 260, y);
      doc.text(`$${parseFloat(tx.amount_usd).toLocaleString()}`, 350, y);
      doc.text(tx.status.toUpperCase(), 440, y);
      doc.text(refStr, 500, y);

      y += 18;
    }

    // Footer
    doc.fillColor('#94a3b8').fontSize(8).text(
      'This document is generated by Fichain Pro Institutional Engine for academic and simulation purposes. Cryptographically verifiable.',
      40,
      780,
      { align: 'center', width: 515 }
    );

    doc.end();
  }
}

module.exports = new StatementService();
